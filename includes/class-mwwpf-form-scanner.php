<?php
/**
 * Lists the file fields of a form by parsing its content.
 *
 * @package MWWPF_File_Upload
 */

defined( 'ABSPATH' ) || exit;

/**
 * Form scanner.
 *
 * The list built here is the allowlist for upload, validation and mail:
 * a field name that is not in it is always rejected.
 */
class MWWPF_Form_Scanner {

	/**
	 * MW WP Form post type.
	 */
	const FORM_POST_TYPE = 'mw-wp-form';

	/**
	 * Shortcode name => field type.
	 */
	const SHORTCODES = array(
		'mwform_file'  => 'file',
		'mwform_image' => 'image',
	);

	/**
	 * Request-level cache, keyed by form ID.
	 *
	 * @var array<int, array>
	 */
	private static $cache = array();

	/**
	 * Returns the file fields of a form.
	 *
	 * @param int $form_id Form (post) ID.
	 * @return array<string, array{type: string, atts: array}> Keyed by field name.
	 */
	public static function get_fields( $form_id ) {
		$form_id = (int) $form_id;
		if ( $form_id <= 0 ) {
			return array();
		}

		if ( isset( self::$cache[ $form_id ] ) ) {
			return self::$cache[ $form_id ];
		}

		$fields = array();
		$post   = get_post( $form_id );

		if ( $post && self::FORM_POST_TYPE === $post->post_type ) {
			$fields = self::parse( $post->post_content );
		}

		/**
		 * Filters the file fields of a form.
		 *
		 * Use this for forms whose content is generated by a filter at render time.
		 *
		 * @param array $fields  Fields keyed by name: [ 'type' => 'file'|'image', 'atts' => array ].
		 * @param int   $form_id Form ID.
		 */
		$fields = apply_filters( 'mwwpf_form_fields', $fields, $form_id );

		$valid = array();
		if ( is_array( $fields ) ) {
			foreach ( $fields as $name => $field ) {
				if ( ! self::is_valid_name( $name ) || ! isset( $field['type'] ) || ! in_array( $field['type'], self::SHORTCODES, true ) ) {
					continue;
				}
				$valid[ $name ] = array(
					'type' => $field['type'],
					'atts' => isset( $field['atts'] ) && is_array( $field['atts'] ) ? $field['atts'] : array(),
				);
			}
		}

		self::$cache[ $form_id ] = $valid;
		return $valid;
	}

	/**
	 * Returns one field, or null when the form does not have it.
	 *
	 * @param int    $form_id Form ID.
	 * @param string $name    Field name.
	 * @return array{type: string, atts: array}|null
	 */
	public static function get_field( $form_id, $name ) {
		if ( ! is_string( $name ) || ! self::is_valid_name( $name ) ) {
			return null;
		}
		$fields = self::get_fields( $form_id );
		return isset( $fields[ $name ] ) ? $fields[ $name ] : null;
	}

	/**
	 * Whether a field name has an acceptable format.
	 *
	 * @param mixed $name Field name.
	 * @return bool
	 */
	public static function is_valid_name( $name ) {
		return is_string( $name ) && '' !== $name && 1 === preg_match( '/^[A-Za-z0-9_\-\[\]]+$/', $name );
	}

	/**
	 * Converts a form key (mw-wp-form-{ID}) to a form ID.
	 *
	 * @param mixed $form_key Form key.
	 * @return int Form ID, or 0 when the key is invalid.
	 */
	public static function form_id_from_key( $form_key ) {
		if ( is_string( $form_key ) && preg_match( '/^' . preg_quote( self::FORM_POST_TYPE, '/' ) . '-(\d+)$/', $form_key, $matches ) ) {
			return (int) $matches[1];
		}
		return 0;
	}

	/**
	 * Clears the request-level cache.
	 */
	public static function flush() {
		self::$cache = array();
	}

	/**
	 * Parses form content.
	 *
	 * @param string $content Form content.
	 * @return array
	 */
	private static function parse( $content ) {
		$fields = array();
		$regex  = get_shortcode_regex( array_keys( self::SHORTCODES ) );

		if ( ! preg_match_all( '/' . $regex . '/s', (string) $content, $matches, PREG_SET_ORDER ) ) {
			return $fields;
		}

		foreach ( $matches as $match ) {
			// Escaped shortcode: [[mwform_file]].
			if ( '[' === $match[1] && ']' === $match[6] ) {
				continue;
			}

			$atts = shortcode_parse_atts( $match[3] );
			if ( ! is_array( $atts ) || ! isset( $atts['name'] ) || ! self::is_valid_name( $atts['name'] ) ) {
				continue;
			}

			$name = $atts['name'];
			if ( ! isset( $fields[ $name ] ) ) {
				$fields[ $name ] = array(
					'type' => self::SHORTCODES[ $match[2] ],
					'atts' => $atts,
				);
			}
		}

		return $fields;
	}
}
